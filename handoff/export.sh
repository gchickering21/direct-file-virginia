#!/usr/bin/env bash
# Export the Virginia change set for a state team, into a folder that is self-contained:
#
#   virginia.patch   one patch that turns IRS-Public/form-builder-examples' direct-file application, at the
#                    commit IRS_PINS.md pins, into virginia/direct-file as committed here
#   CHANGELOG.md     the commits that built the Virginia site, oldest first: each names the rule, the law,
#                    the figure and its source, and what the test proves
#   SOURCES.md       report/SOURCES.md with a one-line header, so the folder carries its own sources
#
#   handoff/export.sh [out-dir]          # default: handoff/patches
#
# In a fresh clone of the IRS repository at the pin:
#   git clone https://github.com/IRS-Public/form-builder-examples.git && cd form-builder-examples
#   git checkout <pinned commit, see IRS_PINS.md>
#   git apply --directory=direct-file --index <out-dir>/virginia.patch
#
# The patch is a diff of two trees, the IRS application at the pin and the Virginia site at HEAD, so it
# is relative to the application folder and knows nothing about this repository's layout. It is
# commit-based: uncommitted edits are not in it. handoff/verify.sh proves it applies.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT="${1:-handoff/patches}"
APP=virginia/direct-file
die() { echo "export.sh: $*" >&2; exit 1; }

# The pin, from the one place it is kept, and the newest squash commit for the subtree (`git subtree add
# --squash` writes "Squashed '…/' content"; every `git subtree pull --squash` after it writes "… changes").
PIN=$(awk -F'|' '$2 ~ /`form-builder-examples\/`/ {gsub(/ /,"",$4); print $4}' IRS_PINS.md)
[ -n "$PIN" ] || die "no row for form-builder-examples in IRS_PINS.md"
SQUASH=$(git log --format=%H -E --grep="^Squashed 'form-builder-examples/' (content|changes)" | head -1)
[ -n "$SQUASH" ] || die "no squash commit for form-builder-examples/: was it added with git subtree --squash?"
git rev-parse -q --verify "HEAD:$APP" >/dev/null || die "no $APP in HEAD"

rm -rf "$OUT" && mkdir -p "$OUT"
git diff --binary "$SQUASH:direct-file" "HEAD:$APP" > "$OUT/virginia.patch"
STAT=$(git diff --shortstat "$SQUASH:direct-file" "HEAD:$APP" | sed 's/^ *//')

# The narrative: every commit that touched the Virginia site, wherever it lived, oldest first. The
# subtree merge itself is left out (--no-merges).
{
  echo "# The Virginia change set, commit by commit"
  echo
  echo "<!-- Generated by handoff/export.sh on $(date +%F) from the git log; edit the commits, not this file. -->"
  echo
  echo "On IRS-Public/form-builder-examples at $PIN. Oldest first; each commit names the rule, the law, the figure"
  echo "and what the test proves. The whole change set is \`virginia.patch\` beside this file."
  echo
  git log --reverse --no-merges --format='## %s%n%n%b' "$SQUASH"..HEAD -- form-builder-examples/direct-file "$APP"
} > "$OUT/CHANGELOG.md"
{ echo "<!-- Generated by handoff/export.sh from report/SOURCES.md on $(date +%F); edit the original. -->"; echo; cat report/SOURCES.md; } > handoff/SOURCES.md
COMMITS=$(git log --no-merges --format=%h "$SQUASH"..HEAD -- form-builder-examples/direct-file "$APP" | wc -l | tr -d ' ')
echo "$OUT/virginia.patch ($STAT) on IRS-Public/form-builder-examples at $PIN; CHANGELOG.md ($COMMITS commits); handoff/SOURCES.md refreshed"
